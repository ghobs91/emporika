// ── Brand catalog ───────────────────────────────────────────────────────
//
// Brands are the layer that makes the matrix combinatorial instead of
// hand-written: a recipient's age / lean / interests pick the brands that fit,
// and each brand contributes a concrete `"<brand> <product noun>"` search.
// ~190 brands × 1–3 nouns is a few hundred searchable gift ideas on its own.
//
// PROVENANCE
// ----------
// Membership and the `strength`/`tier` values are editorial: a list of brands
// that are prominent in their category, not a measured demographic index.
// What *is* measured is whether each brand actually has live listings, and how
// established those listings look, via `scripts/probe-brand-catalog.ts` →
// `docs/gift-brand-evidence.json`. A brand that probe shows no retailer
// presence for should be removed, not kept on conviction.
//
// `ages` is gift-plausibility (who you would buy this for), not a marketing
// segment. `lean` is an aisle observation, bounded to a ±0.04 nudge.

import type { AgeBracket, BrandProfile, GiftTier, InterestId, Lean } from './types';

// ── Age presets ────────────────────────────────────────────────────────

const TEEN_UP: AgeBracket[] = ['teen', 'young_adult', 'adult', 'mature_adult', 'senior'];
const ADULT_UP: AgeBracket[] = ['young_adult', 'adult', 'mature_adult', 'senior'];
const ADULTS: AgeBracket[] = ['adult', 'mature_adult', 'senior'];
const KID_UP: AgeBracket[] = ['child', 'tween', 'teen', 'young_adult', 'adult', 'mature_adult', 'senior'];
const TWEEN_UP: AgeBracket[] = ['tween', 'teen', 'young_adult', 'adult', 'mature_adult', 'senior'];

function b(
  name: string,
  categories: string,
  tier: GiftTier,
  strength: number,
  lean: Lean,
  ages: AgeBracket[],
  interests: string
): BrandProfile {
  return {
    name,
    slug: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
    categories: categories.split('|'),
    tier,
    strength,
    lean,
    ages,
    interests: (interests ? interests.split('|') : []) as InterestId[],
  };
}

