// ── Gift recipient index (checked-in data, no inference at runtime) ──────
//
// This is the file that makes the "Gift Genie" feature work without an LLM.
// Given a recipient's gender, age and interests it yields concrete search
// intents (real retailer queries), each tagged with an age-appropriateness
// window, a gift price tier, and a one-line justification.
//
// PROVENANCE — read this before trusting a number
// -------------------------------------------------
// The structure (age windows, tier, exclusions) is editorial: it encodes
// retail and child-safety conventions, not survey data about people.
// `strength` is an editorial rank, NOT a probability and NOT learned from
// usage. `lean` is an aisle-merchandising observation (±0.04 nudge only;
// see `./brief.ts`), never a claim about a person.
//
// QUERY CONTRACT
// -------------------------------------------------
// Every `query` must return real listings from the configured retailers.
// `scripts/probe-gift-index.mjs` verifies this against the live providers
// and writes `docs/gift-index-evidence.json`. Adding an intent means
// re-running that probe — a query that returns nothing is a bug, not an
// opinion.
//
// To extend: add an intent under an existing interest, or a new
// `InterestProfile` plus its id in `./types.ts` INTEREST_IDS and a label in
// `./taxonomy.ts`. `tests/search/gift-index.test.ts` enforces consistency.

